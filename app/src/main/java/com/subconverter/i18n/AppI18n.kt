package com.subconverter.i18n

import android.content.Context
import java.util.Locale

object AppI18n {
    fun text(context: Context, zh: String): String {
        if (!isEnglish(context)) return zh
        return english[zh] ?: zh
    }

    fun format(context: Context, zhFormat: String, vararg args: Any): String =
        text(context, zhFormat).format(locale(context), *args)

    fun message(context: Context, raw: String): String {
        if (raw.isBlank() || !isEnglish(context)) return raw
        english[raw]?.let { return it }
        regexMessages.forEach { (regex, replace) ->
            regex.matchEntire(raw)?.let { return replace(it) }
        }
        return raw
    }

    private fun isEnglish(context: Context): Boolean =
        locale(context).language.equals(Locale.ENGLISH.language, ignoreCase = true)

    private fun locale(context: Context): Locale =
        context.resources.configuration.locales[0] ?: Locale.getDefault()

    private val regexMessages = listOf<Pair<Regex, (MatchResult) -> String>>(
        Regex("""已添加订阅 #(\d+)""") to { "Subscription #${it.groupValues[1]} added" },
        Regex("""刷新成功，节点解析 (\d+)/(\d+)""") to { "Refreshed, node DNS ${it.groupValues[1]}/${it.groupValues[2]}" },
        Regex("""刷新成功，节点解析 (\d+)/(\d+)（(\d+) 失败）""") to {
            "Refreshed, node DNS ${it.groupValues[1]}/${it.groupValues[2]} (${it.groupValues[3]} failed)"
        },
        Regex("""Gist 部分成功 (\d+)/(\d+)""") to { "Gist partially succeeded ${it.groupValues[1]}/${it.groupValues[2]}" },
        Regex("""Gist 上传失败: (.+)""") to { "Gist upload failed: ${it.groupValues[1]}" },
    )

